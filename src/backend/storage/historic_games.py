def get_random_historic_position() -> HistoricPosition:
    """Returns a randomly selected historic position."""
    return random.choice(HISTORIC_POSITIONS)


def get_historic_position_by_id(position_id: str) -> HistoricPosition | None:
    """Finds a historic position by unique identifier."""
    for pos in HISTORIC_POSITIONS:
        if pos.id == position_id:
            return pos
    return None
